"""Cryptographic approval-token generation and constant-time validation.

Module responsibility:
    Provides the two-step human-approval gate used before destructive remediation
    actions: ``generate_approval_token`` creates a single-use secret token for
    out-of-band delivery to the operator; ``validate_approval_token`` compares a
    provided token against the expected value using constant-time comparison to
    prevent timing-oracle attacks.

System placement:
    Called by ``proxy_remediation.py`` and ``proxy_guardian.py`` when
    ``requires_confirmation=True`` and the policy outcome is
    ``REQUIRE_TYPED_CONFIRMATION``.  Tokens are not persisted by this module;
    callers are responsible for short-lived storage and single-use enforcement.

Key invariants:
    Validation always returns ``False`` when either argument is empty or blank;
    no implicit trust is granted to empty tokens.

Side effects:
    Reads from the OS CSPRNG via the ``secrets`` module on each
    ``generate_approval_token`` call.

Failure modes:
    ``secrets`` relies on the OS entropy pool.  On extremely resource-constrained
    systems this may block briefly; no timeout is applied by this module.
"""

from __future__ import annotations

import secrets


def generate_approval_token() -> str:
    """Return a 32-character hexadecimal cryptographically random approval token.

    The token is generated from the OS CSPRNG (``secrets.token_hex``) and is
    suitable for out-of-band delivery to the operator as a typed confirmation
    gate before destructive remediation.

    Returns:
        A 32-character hex string (16 random bytes).
    """
    return secrets.token_hex(16)


def validate_approval_token(provided: str, expected: str) -> bool:
    """Validate an operator-supplied approval token against the expected value.

    Uses ``secrets.compare_digest`` for constant-time comparison to prevent
    timing-oracle attacks.  Both arguments are stripped of surrounding whitespace
    before comparison.

    Args:
        provided: Token string typed by the operator.
        expected: Token previously generated by ``generate_approval_token``.

    Returns:
        ``True`` if both strings are non-empty and match byte-for-byte after
        whitespace stripping; ``False`` otherwise (including when either is empty).
    """
    if not provided or not expected:
        return False
    return secrets.compare_digest(provided.strip(), expected.strip())
