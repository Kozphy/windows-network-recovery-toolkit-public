"""Typed evidence models for the Endpoint Reliability Decision Platform.

Module responsibility:
    Define the canonical Pydantic models that carry all evidence through the
    platform pipeline: individual ``EvidenceEvent`` records and the
    ``EvidenceBundle`` that groups them for a single incident.

System placement:
    These models are the shared data contract between the ``evidence``
    (collection/conversion), ``decision`` (hypothesis ranking), and
    ``platform`` (API/store) layers.  They are also serialised into audit
    JSONL records.

Key invariants:
    * ``confidence`` is bounded to ``[0.0, 1.0]`` by Pydantic validation; it
      represents ordinal analytic confidence, not a calibrated probability.
    * ``EvidenceEvent.dedupe_key()`` is used exclusively for de-duplication
      within ``TimelineBuilder.build()`` — not as a persistence key.
    * ``EvidenceBundle.to_timeline_json()`` returns only the fields needed for
      the read-only timeline view; full raw data stays in ``events``.
    * Observation ≠ proof: fields such as ``process_name`` and
      ``registry_path`` record what was observed, not what caused the incident.

Side effects:
    None — pure data models with no I/O.
"""

from __future__ import annotations

from typing import Any, Literal

from pydantic import BaseModel, Field

Severity = Literal["low", "medium", "high", "critical"]


class EvidenceEvent(BaseModel):
    """A single, normalised evidence observation from any collector source.

    Each event captures one signal observation from one source at one point in
    time.  Multiple events for the same (timestamp, signal, observed_value)
    triple are considered duplicates and collapsed by ``TimelineBuilder``.

    Attributes:
        event_id: Unique event identifier (UUID string).
        timestamp: ISO-8601 UTC timestamp of observation.
        source: Provenance label (e.g. ``"collector"``, ``"fixture"``,
            ``"timeline"``).
        category: Broad grouping tag (e.g. ``"collector"``, ``"signal"``,
            ``"timeline"``).
        signal: Canonical signal name (e.g. ``"PROXY_ENABLE"``,
            ``"REGISTRY_VALUE_SET"``).
        observed_value: Raw observed value as a string; stored verbatim.
        expected_value: Baseline / expected value for drift comparison; empty
            when no baseline is known.
        process_name: Name of the process that generated the signal, if known.
        pid: Process ID, if known.
        command_line: Full command line, if captured.
        registry_path: Registry key path, if the signal originates from
            registry activity.
        local_address: Local network address observed, if applicable.
        remote_address: Remote network address observed, if applicable.
        port: Network port, if applicable.
        confidence: Ordinal analytic confidence in ``[0.0, 1.0]``.  Not a
            calibrated probability.
        severity: Ordinal severity tier.  Defaults to ``"medium"``.
        raw_data: Full original payload stored for audit traceability.
    """

    event_id: str
    timestamp: str
    source: str
    category: str
    signal: str
    observed_value: str = ""
    expected_value: str = ""
    process_name: str = ""
    pid: int | None = None
    command_line: str = ""
    registry_path: str = ""
    local_address: str = ""
    remote_address: str = ""
    port: int | None = None
    confidence: float = Field(default=0.0, ge=0.0, le=1.0)
    severity: Severity = "medium"
    raw_data: dict[str, Any] = Field(default_factory=dict)

    def dedupe_key(self) -> tuple[str, str, str]:
        """Return a tuple used to identify duplicate observations.

        Returns:
            ``(timestamp, signal, observed_value)`` — the minimal triple that
            uniquely identifies a repeated observation within a timeline.
        """
        return (self.timestamp, self.signal, self.observed_value)


class EvidenceBundle(BaseModel):
    """A deduplicated, chronologically ordered collection of evidence events.

    Produced by ``TimelineBuilder.build()`` and carried through the pipeline
    to the decision and platform layers.

    Attributes:
        incident_id: Unique incident identifier (generated by
            ``TimelineBuilder`` or supplied by the caller).
        created_at: ISO-8601 UTC timestamp of bundle creation.
        host_id: Endpoint identifier; defaults to ``"local"`` for single-host
            analysis.
        events: Ordered list of deduplicated ``EvidenceEvent`` records.
        summary: Optional human-readable summary written by the pipeline.
        tags: Optional classification or routing tags.
    """

    incident_id: str
    created_at: str
    host_id: str = "local"
    events: list[EvidenceEvent] = Field(default_factory=list)
    summary: str = ""
    tags: list[str] = Field(default_factory=list)

    def to_timeline_json(self) -> list[dict[str, Any]]:
        """Return a read-only timeline representation suitable for API responses.

        Includes only the fields needed for UI/audit display (timestamp, signal,
        observed_value, severity).  Full event data remains available via
        ``events``.  Events are sorted chronologically by timestamp string.

        Returns:
            List of dicts with keys ``timestamp``, ``signal``,
            ``observed_value``, and ``severity``.
        """
        return [
            {
                "timestamp": ev.timestamp,
                "signal": ev.signal,
                "observed_value": ev.observed_value,
                "severity": ev.severity,
            }
            for ev in sorted(self.events, key=lambda e: e.timestamp)
        ]
